std::string id_for(int element) { return element == 2 || element == 1 ? "grand_firestorm" : "grand_upheaval"; }

void ensure_defs() {
	if (Moves::defs().has("grand_upheaval")) return;
	Dict up = base_def(0, "Upheaval", "The ground erupts into a 16 m ridge along your aim and throws everyone on it.");
	up.set("startup", 0.45);
	up.set("active", 0.9);
	up.set("anim", dstr(Moves::defs().get("rising_fangs").as_dict(), "anim", "mv_ground_slap"));
	up.set("threat", D({{"cls", "spikes"}}));
	Moves::register_def("grand_upheaval", up);
	// the firestorm reuses the flame-line machinery (FireFlame::line_execute + line_tick) at grand scale: 7 heads 40 deg apart
	// overlap (4.5 m wide, at most 3.6 m apart at 30 m), so the front and the burning band behind it are one continuous wall;
	// 7 x 3 trail fields + 7 heads stay under Sim::MAX_BODIES
	Dict fs = Moves::defs().get("fire_line").as_dict().duplicate(true);
	fs.erase("tiers");
	fs.erase("hook_execute");
	const Dict b = base_def(2, "Firestorm", "A 40 degree wall of flame rolls 30 m out and leaves the ground burning.");
	for (const auto& kv : b) fs.set(kv.first, kv.second);
	for (const auto& kv : D({{"startup", 0.55}, {"active", 0.35}, {"heat", 0.0}, {"lines", 7}, {"spread", 40.0}, {"width", 4.5},
	                         {"budget", 30.0}, {"speed", 13.0}, {"steer", 0.0}, {"damage", 22.0}, {"balance", 60.0}, {"knock", 7.0},
	                         {"lift", 5.0}, {"trail_every", 10.0}, {"trail_r", 3.4}, {"trail_life", 6.0}, {"trail_share", 0.15},
	                         {"hit_status_t", 3.0}}))
		fs.set(kv.first, kv.second);
	Moves::register_def("grand_firestorm", fs);
}

void on_start(CombatWorld& w, ActorState& a, ActionInst& inst, const ActorIntent& it) {
	if (a.surge < kSurgeMax - 1e-6) {
		w.emit("insufficient", D({{"actor", a.id}, {"what", "surge"}, {"move", inst.id}}));
		w.finish_action(a, inst);
		return;
	}
	a.surge = 0.0;
	const Vec3 dir = aim_of(w, a, it);
	inst.data.set("dir", dir);
	inst.data.set("face", dir);
	inst.data.set("aim", dir);
	inst.data.set("origin", a.pos);
	inst.data.set("seg_done", 0);
	inst.heavy = true;
	w.emit("grand", D({{"actor", a.id}, {"kind", inst.id == "grand_firestorm" ? "firestorm" : "upheaval"}, {"phase", "gather"},
	                   {"pos", a.pos}, {"dir", dir}}));
}

ActionPhase after_startup(CombatWorld&, ActorState&, ActionInst&, const ActorIntent&) { return ActionPhase::Active; }

void on_phase(CombatWorld& w, ActorState& a, ActionInst& inst, ActionPhase p) {
	if (p != ActionPhase::Active) return;
	inst.data.set("origin", a.pos);   // the caster may have stepped during the gather
	if (inst.id == "grand_firestorm") {
		w.ledger.generated += kFireHeat;
		inst.data.set("heat_paid", kFireHeat);
		FireFlame::line_execute(w, a, inst);
		int k = 0;
		for (const Value& id : darr(inst.data, "bodies")) {
			if (MatBody* fb = w.get_body(vint(id)); fb != nullptr) {
				fb->props.set("grand", true);   // FX: one continuous wall across the heads of the same storm, in fan order
				fb->props.set("grand_group", inst.attack_id);
				fb->props.set("grand_index", k);
				// odd heads lay their burning ground half a step later: the band behind the front is a checkerboard, no gaps
				if (k % 2 == 1) fb->props.set("last_trail", fb->pos - dvec(inst.data, "dir", a.forward()) * 5.0f);
			}
			++k;
		}
		w.emit("grand", D({{"actor", a.id}, {"kind", "firestorm"}, {"phase", "release"}, {"pos", a.pos}, {"dir", dvec(inst.data, "dir")},
		                   {"length", 30.0}, {"width", 15.0}}));
	}
}

void on_tick(CombatWorld& w, ActorState& a, ActionInst& inst, const ActorIntent&) {
	if (inst.phase != ActionPhase::Active || inst.id != "grand_upheaval") return;
	const double active = dnum(inst.def, "active", 0.9);
	const int due = mini(kRidgeSegments, static_cast<int>(inst.t / (active / kRidgeSegments)) + 1);
	int done = dint(inst.data, "seg_done", 0);
	while (done < due) {
		erupt_segment(w, a, inst, done);
		++done;
	}
	inst.data.set("seg_done", done);
}

void on_interrupt(CombatWorld& w, ActorState&, ActionInst& inst, const std::string&) {
	const double left = dnum(inst.data, "heat_paid", 0.0);
	if (left > 0.0) {
		w.ledger.spent += left;   // generated but never released: booked as spent (Verbs convention)
		inst.data.set("heat_paid", 0.0);
	}
}

