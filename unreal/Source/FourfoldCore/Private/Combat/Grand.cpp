constexpr double kFireHeat = 1600.0;       // HU, generated by the surge (booked in the energy ledger)
constexpr int kRidgeSegments = 6;
constexpr double kRidgeStart = 2.5;        // m ahead of the caster
constexpr double kRidgeLength = 16.0;
constexpr double kRidgeWidth = 3.4;
constexpr double kRidgeHit = 2.4;          // actors this close to the ridge line are thrown
constexpr double kWallMass = 90.0;         // arenas: stone per segment, drawn from the ground ledger

Vec3 aim_of(CombatWorld& w, ActorState& a, const ActorIntent& it) {
	Vec3 d = it.aim_active ? it.aim_dir : Vec3();
	if (d.length() < 0.1f) {
		if (ActorState* t = w.get_actor(a.lock_target); t != nullptr && t != &a) d = t->pos - a.pos;
	}
	d.y = 0.0f;
	return d.length() > 0.1f ? d.normalized() : a.forward();
}

void erupt_segment(CombatWorld& w, ActorState& a, ActionInst& inst, int s) {
	const Vec3 dir = dvec(inst.data, "dir", a.forward());
	const Vec3 o = dvec(inst.data, "origin", a.pos);
	const double t0 = kRidgeStart + kRidgeLength * s / kRidgeSegments;
	const double t1 = kRidgeStart + kRidgeLength * (s + 1) / kRidgeSegments;
	const Vec3 p0 = o + dir * f32(t0);
	const Vec3 p1 = o + dir * f32(t1);
	const Vec3 mid = (p0 + p1) * 0.5f;
	const double h = 2.6 + 1.2 * s / (kRidgeSegments - 1);
	if (w.terrain_live) {
		// open world: the valley itself rises (cut-and-fill: trenches beside the ridge supply the earth)
		const ArenaMap& m = w.arena;
		w.terrain_live->EditRidge(p0.x + m.ox, p0.z + m.oz, p1.x + m.ox, p1.z + m.oz, kRidgeWidth, h);
	} else {
		// arenas: a standing stone wall, drawn from the ground
		const Vec3 at(mid.x, f32(w.arena.ground_height(mid.x, mid.z, mid.y + 0.5)), mid.z);
		MatBody* b = w.spawn_body(Mat::Stone, Form::Wall, kWallMass, at, "ground@" + ftos(at.x, 1) + "," + ftos(at.z, 1));
		w.mass_ledger.ground_taken += kWallMass;
		b->tag = "grand_ridge";
		b->wall_yaw = std::atan2(static_cast<double>(dir.x), static_cast<double>(dir.z)) + 1.5707963267948966;
		b->wall_half = V3((t1 - t0) * 0.5, h * 0.5, 0.8);
		b->wall_rise = 0.0;
		b->static_body = true;
		b->on_ground = true;
		b->max_life = -1.0;
		b->hardness = 6.0;
		b->props.set("standing", 8.0);
		b->props.set("rise_time", 0.15);
		b->props.set("source", "ground");
		b->last_actor = a.id;
		w.emit("wall", D({{"actor", a.id}, {"body", b->id}, {"tag", "grand_ridge"}}));
	}
	// everyone on or beside the rising ground is thrown (once per technique: one attack id)
	const Vec3 seg = p1 - p0;
	const double len2 = static_cast<double>(seg.x) * seg.x + static_cast<double>(seg.z) * seg.z;
	for (size_t i = 0; i < w.actors.size(); ++i) {
		ActorState& t = *w.actors[i];
		if (&t == &a || t.health <= 0.0) continue;
		double u = len2 > 1e-9 ? ((t.pos.x - p0.x) * seg.x + (t.pos.z - p0.z) * seg.z) / len2 : 0.0;
		u = clampf(u, 0.0, 1.0);
		const Vec3 near_pt = p0 + seg * f32(u);
		Vec3 away = t.pos - near_pt;
		away.y = 0.0f;
		const double d = away.length();
		if (d > kRidgeHit || t.pos.y > w.arena.ground_height(t.pos.x, t.pos.z, t.pos.y + 0.5) + 1.2) continue;
		away = d > 0.05 ? away / f32(d) : Vec3(dir.z, 0.0f, -dir.x);
		w.hit_actor(t, D({{"attack_id", inst.attack_id}, {"attacker", a.id}, {"damage", 20.0}, {"balance", 80.0},
		                  {"knock", away * 3.5f + Vec3(0.0f, 9.5f, 0.0f)}, {"kind", "stone"}, {"from", mid}, {"power", 60.0},
		                  {"tier", 3}, {"mat", "stone"}}));
	}
	w.emit("grand", D({{"actor", a.id}, {"kind", "upheaval"}, {"segment", s}, {"from", p0}, {"to", p1}, {"height", h}}));
	FxEvents::fx(w, "erupt", "stone", D({{"actor", a.id}, {"pos", mid}, {"dir", dir}, {"radius", kRidgeWidth}, {"element", 0}}));
}

Dict base_def(int element, const std::string& name, const std::string& desc) {
	return D({{"element", element}, {"sub", 0}, {"slot", "grand"}, {"name", name}, {"desc", desc}, {"module", "grand"},
	          {"recovery", 0.7}, {"cost", 0.0}});
}
